import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dist = resolve(root, 'dist');
const serverDir = resolve(dist, 'server');

const [page, baseStyles, communityStyles, client, apiModule, manifest] = await Promise.all([
  readFile(resolve(root, 'src/index.html'), 'utf8'),
  readFile(resolve(root, 'src/styles/base.css'), 'utf8'),
  readFile(resolve(root, 'src/styles/community.css'), 'utf8'),
  readFile(resolve(root, 'src/app.js'), 'utf8'),
  readFile(resolve(root, 'worker/api.js'), 'utf8'),
  readFile(resolve(root, '.openai/hosting.json'), 'utf8'),
]);

const styles = `${baseStyles}\n${communityStyles}`;
const apiSource = apiModule.replace(/\nexport \{ handleApi \};\s*$/, '');
const entry = `// Generated by scripts/build.mjs. Edit src/* and worker/api.js instead.\n` +
  `const page = ${JSON.stringify(page)};\n` +
  `const styles = ${JSON.stringify(styles)};\n` +
  `const client = ${JSON.stringify(client)};\n\n` +
  `${apiSource}\n\n` +
  `export default {\n` +
  `  async fetch(request, env) {\n` +
  `    const url = new URL(request.url);\n` +
  `    if (url.pathname.startsWith('/api/')) return handleApi(request, env, url);\n` +
  `    if (url.pathname === '/assets/styles.css') return new Response(styles, { headers: { 'content-type': 'text/css; charset=utf-8', 'cache-control': 'public, max-age=3600' } });\n` +
  `    if (url.pathname === '/assets/app.js') return new Response(client, { headers: { 'content-type': 'text/javascript; charset=utf-8', 'cache-control': 'public, max-age=3600' } });\n` +
  `    if (url.pathname === '/' || url.pathname === '/index.html') return new Response(page, { headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'public, max-age=300', 'x-content-type-options': 'nosniff', 'referrer-policy': 'strict-origin-when-cross-origin' } });\n` +
  `    return new Response('Not found', { status: 404 });\n` +
  `  }\n` +
  `};\n`;

await rm(dist, { recursive: true, force: true });
await mkdir(serverDir, { recursive: true });
await mkdir(resolve(dist, '.openai'), { recursive: true });
await writeFile(resolve(serverDir, 'index.js'), entry);
await writeFile(resolve(dist, '.openai/hosting.json'), manifest);

console.log(`Built ${dist} from src/ and worker/api.js`);
